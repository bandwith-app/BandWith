/** Text → columns of 7 booleans (1 blank column between glyphs). */
export function textColumns(text: string): boolean[][] {
  const cols: boolean[][] = [];
  for (const ch of text.toUpperCase()) {
    const g = (GLYPHS[ch] ?? GLYPHS[' ']).split('/');
    for (let x = 0; x < 5; x++) cols.push(g.map((row) => row[x] === '1'));
    cols.push([false, false, false, false, false, false, false]);
  }
  return cols;
}

/** Static dot-matrix SVG, lit dots in currentColor. */
export function dotSvg(text: string, offOpacity = 0.12): string {
  const cols = textColumns(text);
  if (cols.length) cols.pop();
  const w = cols.length * 2;
  let dots = '';
  cols.forEach((col, x) => col.forEach((on, y) => {
    dots += `<circle cx="${x * 2 + 1}" cy="${y * 2 + 1}" r="0.78" fill="currentColor"${on ? '' : ` opacity="${offOpacity}"`}/>`;
  }));
  return `<svg viewBox="0 0 ${w} 14" aria-hidden="true">${dots}</svg>`;
}

/** Draw dot text into a canvas (used on the pass). */
export function drawDots(canvas: HTMLCanvasElement, text: string, color: string, offColor: string) {
  const dpr = Math.min(window.devicePixelRatio || 1, 2);
  const cssW = canvas.clientWidth || 100;
  const cssH = canvas.clientHeight || 24;
  canvas.width = cssW * dpr;
  canvas.height = cssH * dpr;
  const ctx = canvas.getContext('2d');
  if (!ctx) return;
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.clearRect(0, 0, cssW, cssH);
  const cols = textColumns(text);
  const step = cssH / 7;
  const r = step * 0.38;
  cols.forEach((col, x) => col.forEach((on, y) => {
    ctx.fillStyle = on ? color : offColor;
    ctx.beginPath();
    ctx.arc(x * step + step / 2, y * step + step / 2, r, 0, Math.PI * 2);
    ctx.fill();
  }));
}

/**
 * Writes docs/lifecycles: one page per lifecycle model (Mermaid state
 * diagram, what each state must show, what each event does, the generated
 * paths, known bugs and manual checks) and the README index.
 *
 *   pnpm e2e:models:docs           write the pages
 *   pnpm e2e:models:docs --check   fail when a page is out of date
 *
 * Plain `node` (type stripping): no Playwright, no browser.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MODELS } from './index.ts';
import { generatePaths, runnable, transitionsOf, type EventSpec, type Lifecycle, type StateSpec } from './lifecycle.ts';
import { coverageOf } from './coverage.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DOCS = join(ROOT, 'docs', 'lifecycles');

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** A Mermaid stateDiagram-v2 of the model; known-bug transitions are marked. */
export function mermaidOf(model: Lifecycle): string {
  const lines = ['stateDiagram-v2', `  [*] --> ${model.initial}`];
  const bugEdges = new Set<string>();
  for (const b of model.knownBugs) {
    const events = b.path.split(' ');
    let at = model.initial as string;
    for (const e of events) {
      const next = (model.states as Record<string, StateSpec<string, string>>)[at]?.on?.[e];
      if (!next) break;
      if (e === events[events.length - 1]) bugEdges.add(`${at} ${e}`);
      at = String(next);
    }
  }
  for (const t of transitionsOf(model)) {
    const bug = bugEdges.has(`${t.from} ${t.event}`) ? ' (known bug)' : '';
    lines.push(`  ${t.from} --> ${t.to} : ${t.event}${bug}`);
  }
  for (const [name, st] of Object.entries(model.states) as [string, StateSpec<string, string>][]) {
    if (!st.on || !Object.keys(st.on).length) lines.push(`  ${name} --> [*]`);
  }
  return lines.join('\n');
}

function page(model: Lifecycle): string {
  const cov = coverageOf(model);
  const { paths } = generatePaths(model);
  const out: string[] = [];
  out.push(`# ${model.title}`, '');
  out.push(`<!-- Generated by \`pnpm e2e:models:docs\` from the model \`${model.id}\` in e2e/models. Do not edit by hand. -->`, '');
  out.push(model.summary, '');
  out.push(`Starts as **${model.role}**. States ${cov.coveredStates}/${cov.states} and transitions ${cov.coveredTransitions}/${cov.transitions} covered by ${cov.paths} generated paths (${cov.tests} Playwright tests).`, '');
  if (model.variants?.length) {
    out.push(`Runs for each of: ${model.variants.join(', ')}${model.rotateVariants ? ' (one per path, in turn; every one for ' + (model.everyVariant ?? []).map((k) => `\`${k}\``).join(', ') + ')' : ''}.`, '');
  }
  out.push('```mermaid', mermaidOf(model), '```', '');
  out.push('## States', '', '| State | The user sees |', '| --- | --- |');
  for (const [name, st] of Object.entries(model.states) as [string, StateSpec<string, string>][]) {
    out.push(`| \`${name}\` | ${cell(st.see)}${st.source ? ` *(${cell(st.source)})*` : ''} |`);
  }
  out.push('', '## Events', '', '| Event | The user does |', '| --- | --- |');
  for (const [name, ev] of Object.entries(model.events) as [string, EventSpec][]) {
    out.push(`| \`${name}\` | ${cell(ev.do)}${ev.only ? ` *(only on ${ev.only.join(', ')})*` : ''} |`);
  }
  const withVariants = !!model.variants?.length;
  out.push('', '## Generated paths', '', `| Test | Profiles |${withVariants ? ' Variants |' : ''}`, `| --- | --- |${withVariants ? ' --- |' : ''}`);
  for (const p of paths) {
    const off = p.profiles.filter((profile) => !runnable(p, profile).length);
    const bug = !off.length ? '' : off.length === p.profiles.length ? ' **(known bug: not run)**' : ` **(known bug: not run on ${off.join(', ')})**`;
    out.push(`| ${cell(p.name)}${bug} | ${p.profiles.join(', ')} |${withVariants ? ` ${p.variants.join(', ')} |` : ''}`);
  }
  if (model.knownBugs.length) {
    out.push('', '## Known bugs', '');
    for (const b of model.knownBugs) {
      out.push(`- **${b.path}**${b.variant ? ` (${b.variant})` : ''} — ${b.role}, ${b.profile}${b.onlyOn ? ` (left out only on ${b.onlyOn.join(', ')})` : ''}`);
      out.push(`  - Actual: ${b.actual}`);
      out.push(`  - Expected: ${b.expected}`);
      out.push(`  - Evidence: \`${b.evidence}\` (local, re-create with \`E2E_KNOWN_BUGS=1\`)`);
    }
  }
  if (model.manual?.length) {
    out.push('', '## Not in the demo (manual)', '');
    for (const m of model.manual) out.push(`- ${m}`);
  }
  return `${out.join('\n')}\n`;
}

function readme(): string {
  const rows = MODELS.map(coverageOf);
  const out: string[] = [];
  out.push('# Lifecycle models', '');
  out.push('<!-- Generated by `pnpm e2e:models:docs`. Do not edit by hand. -->', '');
  out.push(
    'The riskiest multi-step lifecycles of BandWith, written as XState state machines **for tests only** (the app does not use XState). Each model is derived from the code, the migrations and the Academy; its states say what the user must see, its events what the user does. `@xstate/graph` generates one path per transition (shortest way to its source state, then the transition; prefixes of longer paths dropped), and every path runs as a Playwright test on the demo build (`e2e/specs/xstate-lifecycles.spec.ts`).',
    '',
  );
  out.push('| Model | Role | States | Transitions | Paths | Tests | Known bugs |', '| --- | --- | --- | --- | --- | --- | --- |');
  for (const r of rows) {
    out.push(`| [${r.title}](${r.id}.md) | ${r.role} | ${r.coveredStates}/${r.states} | ${r.coveredTransitions}/${r.transitions} | ${r.paths} | ${r.tests} | ${r.knownBugs.length} |`);
  }
  const sum = (k: 'states' | 'transitions' | 'coveredStates' | 'coveredTransitions' | 'paths' | 'tests') => rows.reduce((a, r) => a + r[k], 0);
  out.push(`| **Total** | | ${sum('coveredStates')}/${sum('states')} | ${sum('coveredTransitions')}/${sum('transitions')} | ${sum('paths')} | ${sum('tests')} | ${rows.reduce((a, r) => a + r.knownBugs.length, 0)} |`, '');
  out.push('## Where things live', '');
  out.push('- `e2e/models/lifecycle.ts`: the shared core (`defineLifecycle`, path generation, known bugs).');
  out.push('- `e2e/models/<name>.model.ts`: a model (pure: no Playwright), with the code / migration / Academy sources in its header.');
  out.push('- `e2e/models/<name>.steps.ts`: the Playwright check for every state and the steps for every event.');
  out.push('- `e2e/specs/xstate-lifecycles.spec.ts`: runs every generated path; after each event the target state\'s check runs.');
  out.push('- `e2e/models/coverage.ts` and `e2e/models/mermaid.ts`: the coverage report and these pages.', '');
  out.push('## Run', '', '```sh');
  out.push('pnpm e2e:models:coverage                      # states, transitions, covered, known bugs, manual');
  out.push('pnpm e2e:models:docs                          # rewrite docs/lifecycles (--check in CI-style use)');
  out.push('pnpm e2e lifecycles --project=phone-portrait  # every path');
  out.push('pnpm e2e lifecycles --project=duo-laptop      # the wide subset (also ipad-landscape)');
  out.push('E2E_KNOWN_BUGS=1 pnpm e2e lifecycles --project=phone-portrait  # only the known-bug paths (they fail)');
  out.push('```', '');
  out.push('## Profiles', '');
  out.push('Every path runs on phone-portrait. A model\'s `wide` paths also run on ipad-landscape and duo-laptop (titles tagged `@laptop`). A path whose gesture only one layout allows runs only there (switching overview cards with an edit sheet open: `@duo-book`).', '');
  out.push('## Known bugs', '');
  out.push('A path that fails because the **app** is wrong is listed in the model\'s `knownBugs` (role, profile, steps, evidence, the expected behaviour and its source) and left out of the run, so the suite stays green; the coverage report and the model\'s page print it. A path that fails because the **model** is wrong gets the model fixed.', '');
  const bugs = rows.flatMap((r) => r.knownBugs.map((b) => ({ r, b })));
  if (bugs.length) for (const { r, b } of bugs) out.push(`- [${r.title}](${r.id}.md): \`${b.path}\` — ${b.actual}`);
  else out.push('None.');
  out.push('');
  return out.join('\n');
}

const check = process.argv.includes('--check');
const files: [string, string][] = [[join(DOCS, 'README.md'), readme()], ...MODELS.map((m) => [join(DOCS, `${m.id}.md`), page(m)] as [string, string])];
mkdirSync(DOCS, { recursive: true });
let stale = 0;
for (const [file, text] of files) {
  const now = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (now === text) continue;
  if (check) {
    console.error(`out of date: ${file.slice(ROOT.length + 1)}`);
    stale++;
  } else {
    writeFileSync(file, text);
    console.log(`wrote ${file.slice(ROOT.length + 1)}`);
  }
}
if (stale) {
  console.error('Run pnpm e2e:models:docs');
  process.exit(1);
}
